"""The views of a probe: a markdown table for the documentation and for people,
JSON for agents and tools.

Both are made from an envelope, the model of one or more probes with the
cluster and the source it was read from:

    {"schema": 1, "cluster": "daint", "source": "intended", "emitters": "...",
     "probes": {"partitions": {...}}}

Runs on the login nodes, which provide Python 3.6: no f-strings.
"""
import json
from collections import OrderedDict

from probes import PROBES, SCHEMA
from system import ProbeError


def envelope(cluster, source, emitters, models):
    return OrderedDict([
        ("schema", SCHEMA),
        ("cluster", cluster),
        ("source", source),
        ("emitters", emitters),
        ("probes", models),
    ])


def to_json(data):
    return json.dumps(data, indent=2) + "\n"


def from_json(text):
    data = json.loads(text, object_pairs_hook=OrderedDict)
    if data.get("schema") != SCHEMA:
        raise ProbeError("schema %s, expected %s: run probes/probe.sh on %s"
                         % (data.get("schema"), SCHEMA, data.get("cluster")))
    return data


def header(probe, data):
    """Fragment header. Carries no date and no hostname, so that re-running the
    probes produces an empty diff when the system configuration has not
    changed."""
    sources = probe.sources[data["source"]]
    if data["source"] == "live":
        return ("<!-- Live configuration of %s, read by probes/probe.sh --live from: %s\n"
                "     This can differ from the documentation, which shows the intended configuration. -->\n"
                % (data["cluster"], sources))
    return ("<!-- Generated by probes/probe.sh from: %s\n"
            "     Do not edit. Regenerate by running probes/probe.sh on %s.\n"
            "     cluster: %s  emitters: %s -->\n"
            % (sources, data["cluster"], data["cluster"], data["emitters"]))


def table(probe, model):
    lines = ["| " + " | ".join(title for title, _ in probe.columns) + " |",
             "|" + "---|" * len(probe.columns)]
    for row in probe.rows(model):
        lines.append("| " + " | ".join(cell(row) for _, cell in probe.columns) + " |")
    return "\n".join(lines) + "\n"


def to_markdown(data):
    """The table of each probe in the envelope, each under its header."""
    parts = []
    for name, model in data["probes"].items():
        probe = PROBES[name]
        parts.append(header(probe, data) + "\n" + table(probe, model))
    return "\n".join(parts)


def catalogue():
    """What the probes are, for --list."""
    return OrderedDict([
        ("schema", SCHEMA),
        ("probes", OrderedDict(
            (probe.name, OrderedDict([
                ("scope", probe.scope),
                ("description", probe.description),
                ("sources", probe.sources),
                ("fields", probe.fields),
            ])) for probe in PROBES.values())),
    ])


def catalogue_text():
    lines = []
    for probe in PROBES.values():
        lines.append("%-12s %-7s %s" % (probe.name, probe.scope, probe.description))
    return "\n".join(lines) + "\n"
